test('automatic lobbies start five seconds after both players ready, cancel safely and restart a full countdown',async t=>{
  const host=await client.create(LOBBY.roomType,{name:'Automatic Host',autoStart:true})
  t.after(()=>host.leave().catch(()=>{}))
  await until(()=>host.state?.players?.has(host.sessionId))
  assert.equal(host.state.autoStart,true)
  host.send('ready',{ready:true});await delay(100)
  assert.equal(host.state.countdown,0)
  const guest=await join(t,host.roomId)
  host.send('format',{format:'freeplay'})
  await until(()=>host.state.format==='freeplay')
  host.send('ready',{ready:true});guest.send('ready',{ready:true})
  await until(()=>host.state.phase==='countdown')
  assert.equal(host.state.countdown,5)
  // Repeated ready/start packets cannot shorten or duplicate the countdown.
  host.send('start');host.send('ready',{ready:true})
  guest.send('ready',{ready:false})
  await until(()=>host.state.phase==='forming' && host.state.countdown===0)
  await delay(5100)
  assert.equal(host.state.arenaActive,false)
  const started=Date.now()
  guest.send('ready',{ready:true})
  await until(()=>host.state.phase==='countdown')
  assert.equal(host.state.countdown,5)
  await until(()=>host.state.arenaActive && guest.state.arenaActive,6500)
  assert.ok(Date.now()-started>=4800)
  assert.equal(host.state.arenaEpoch,1)
  guest.send('backToLobby')
  await until(()=>!host.state.arenaActive)
  host.send('ready',{ready:true});guest.send('ready',{ready:true})
  await until(()=>host.state.phase==='countdown')
  await guest.leave()
  await until(()=>host.state.phase==='waiting')
  assert.equal(host.state.countdown,0)
  assert.equal(host.state.players.get(host.sessionId).ready,false)
})

