import { test, expect } from '@playwright/test'
import { state, aimAtTarget } from './helpers.js'

async function resume(page) {
  await page.getByRole('button',{ name:'RESUME / ENTER ARENA' }).click()
  await expect.poll(async () => (await state(page)).mode).toBe('playing')
}
async function pause(page) {
  await page.evaluate(() => document.exitPointerLock())
  await expect.poll(async () => (await state(page)).mode).toBe('paused')
}
async function startRifle(page) {
  await page.goto('/')
  await page.getByRole('button',{ name:/SETTINGS/ }).click()
  await page.getByLabel('Render quality').selectOption('Low')
  await page.getByRole('button',{ name:'BACK' }).click()
  await page.getByRole('button',{ name:/ENTER TRAINING/ }).click()
  await expect(page.getByRole('button',{ name:'RESUME / ENTER ARENA' })).toBeEnabled({ timeout:30000 })
  await resume(page)
  await page.keyboard.press('Digit3')
  await expect(page.getByText('03 / PULSE RIFLE',{ exact:true })).toBeVisible()
  await expect(page.getByText('FULL AUTO · HOLD LEFT CLICK',{ exact:true })).toBeVisible()
}

test('automatic rifle hits, release stops fire, pistol stays semi-auto and magazines reload independently', async ({ page }) => {
  const errors = []
  page.on('pageerror',error => errors.push(error.message))
  await startRifle(page)
  await page.screenshot({ path:'rifle-preview.png' })
  await aimAtTarget(page)
  await page.mouse.down()
  try { await expect.poll(async () => (await state(page)).targets[1].hp,{ intervals:[20] }).toBe(0) }
  finally { await page.mouse.up() }
  const killed = await state(page)
  expect(killed.score).toBe(100)
  expect(killed.hitDamage).toBe(2)
  expect(killed.weaponStats.rifle.hits).toBe(8)
  expect(killed.magazines.rifle).toBe(30-killed.weaponStats.rifle.shots)
  expect(killed.magazines.pistol).toBe(12)
  await page.waitForTimeout(400)
  expect((await state(page)).weaponStats.rifle.shots).toBe(killed.weaponStats.rifle.shots)
  await page.keyboard.press('Digit1'); await page.waitForTimeout(300)
  await page.mouse.down(); await page.waitForTimeout(700); await page.mouse.up()
  expect((await state(page)).weaponStats.pistol.shots).toBe(1)
  expect((await state(page)).magazines.pistol).toBe(11)
  await page.keyboard.press('Digit3'); await page.waitForTimeout(300)
  expect((await state(page)).magazines.rifle).toBe(killed.magazines.rifle)
  await page.keyboard.press('KeyR')
  expect((await state(page)).reloadWeapon).toBe('rifle')
  await page.mouse.down(); await page.waitForTimeout(2300)
  expect((await state(page)).magazines.rifle).toBe(30)
  expect((await state(page)).weaponStats.rifle.shots).toBe(killed.weaponStats.rifle.shots)
  await page.mouse.up()
  expect((await state(page)).magazines.pistol).toBe(11)
  await pause(page)
  await page.getByRole('button',{ name:'RESTART TRAINING',exact:true }).click()
  expect(await state(page)).toMatchObject({ weapon:'pistol',magazines:{ pistol:12,rifle:30,shotgun:6 },weaponStats:{ rifle:{ shots:0,hits:0 } },score:0 })
  expect(errors).toEqual([])
})

test('held rifle input clears on switching, pause, focus loss and reload; empty magazines reload automatically', async ({ page }) => {
  const errors = []
  page.on('pageerror',error => errors.push(error.message))
  await startRifle(page)
  await page.mouse.down()
  await expect.poll(async () => (await state(page)).weaponStats.rifle.shots).toBeGreaterThanOrEqual(3)
  await page.keyboard.press('Digit2')
  const switched = await state(page)
  expect(switched.weapon).toBe('blade')
  await page.waitForTimeout(400)
  await page.keyboard.press('KeyQ') // blade -> rifle; held trigger must stay released
  await page.waitForTimeout(400)
  expect((await state(page)).weapon).toBe('rifle')
  expect((await state(page)).weaponStats.rifle.shots).toBe(switched.weaponStats.rifle.shots)
  expect((await state(page)).swings).toBe(0)
  await page.mouse.up(); await page.mouse.down()
  await expect.poll(async () => (await state(page)).weaponStats.rifle.shots).toBeGreaterThan(switched.weaponStats.rifle.shots)
  await pause(page)
  const paused = await state(page)
  await page.waitForTimeout(350)
  expect((await state(page)).weaponStats.rifle.shots).toBe(paused.weaponStats.rifle.shots)
  expect((await state(page)).time).toBe(paused.time)
  await page.mouse.up(); await resume(page); await page.waitForTimeout(350)
  expect((await state(page)).weaponStats.rifle.shots).toBe(paused.weaponStats.rifle.shots)
  await page.mouse.down()
  await expect.poll(async () => (await state(page)).weaponStats.rifle.shots).toBeGreaterThan(paused.weaponStats.rifle.shots)
  await page.evaluate(() => window.dispatchEvent(new Event('blur')))
  await expect.poll(async () => (await state(page)).mode).toBe('paused')
  const blurred = await state(page)
  await page.waitForTimeout(350)
  expect((await state(page)).weaponStats.rifle.shots).toBe(blurred.weaponStats.rifle.shots)
  await page.mouse.up()
  await page.getByRole('button',{ name:'RESTART TRAINING',exact:true }).click()
  await resume(page); await page.keyboard.press('Digit3'); await page.waitForTimeout(300)
  await page.mouse.down()
  try { await expect.poll(async () => (await state(page)).magazines.rifle,{ timeout:8000,intervals:[30] }).toBe(0) }
  finally { await page.mouse.up() }
  expect((await state(page)).weaponStats.rifle.shots).toBe(30)
  expect((await state(page)).reloadReason).toBe('auto')
  await expect(page.getByRole('status').filter({ hasText:'RELOADING' })).toContainText('AUTO · EMPTY MAGAZINE')
  await page.mouse.down(); await page.waitForTimeout(250)
  expect((await state(page)).weaponStats.rifle.shots).toBe(30)
  await expect.poll(async () => (await state(page)).magazines.rifle).toBe(30)
  expect((await state(page)).magazines.rifle).toBe(30)
  expect((await state(page)).weaponStats.rifle.shots).toBe(30)
  expect((await state(page)).magazines.pistol).toBe(12)
  await expect(page.getByRole('progressbar',{ name:'Reload progress' })).toHaveCount(0)
  await page.waitForTimeout(300)
  expect((await state(page)).weaponStats.rifle.shots).toBe(30)
  await page.mouse.up()
  expect(errors).toEqual([])
})
