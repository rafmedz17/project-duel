import {test,expect} from '@playwright/test'
import {Client} from '@colyseus/sdk'
import {openGame,openMultiplayer,presetLoadout,state} from './helpers.js'

test.beforeEach(async({page})=>{
  await page.emulateMedia({reducedMotion:'reduce'})
  await page.addInitScript(()=>localStorage.setItem('duel-settings',JSON.stringify({quality:'Low'})))
})
const charge=card=>card.evaluate(element=>Number(element.style.getPropertyValue('--skill-charge')))

test('training skill icons refill with the real cooldown, freeze when paused and light up when ready',async({page})=>{
  const errors=[];page.on('pageerror',error=>errors.push(error.message))
  await presetLoadout(page,{character:'vex',unique:'scanner'})
  await openGame(page)
  await page.getByRole('button',{name:/ENTER TRAINING/}).click()
  await page.getByRole('button',{name:'RESUME / ENTER ARENA'}).click()
  await expect(page.locator('.skill-icon-fill svg')).toHaveCount(4)
  await expect(page.getByTestId('ability-ultimate').locator('.skill-icon-fill svg')).toHaveAttribute('data-skill-icon','ultimate-dash')
  const shield=page.getByTestId('ability-shield')
  await page.keyboard.press('KeyF')
  const progress=shield.getByRole('progressbar',{name:'SHIELD cooldown'})
  await expect(progress).toBeAttached()
  const initial=await charge(shield)
  await expect.poll(()=>charge(shield)).toBeGreaterThan(initial+.05)
  await expect(shield).toHaveClass(/cooling/,{timeout:5000})
  await expect.poll(()=>shield.locator('.skill-icon-fill').evaluate(element=>getComputedStyle(element).clipPath)).not.toBe('inset(0px)')
  await page.screenshot({path:'skill-cooldown-preview.png'})
  await page.evaluate(()=>document.exitPointerLock())
  await expect.poll(async()=>(await state(page)).mode).toBe('paused')
  const paused=await charge(shield)
  await page.waitForTimeout(250)
  expect(await charge(shield)).toBe(paused)
  await page.getByRole('button',{name:'RESUME / ENTER ARENA'}).click()
  await expect(shield).toHaveClass(/ready/,{timeout:10000})
  await expect(progress).toHaveCount(0);expect(await charge(shield)).toBe(1)
  await page.keyboard.press('KeyX');await page.keyboard.press('KeyE')
  await expect(page.getByTestId('ability-dash')).toContainText('UNLIMITED')
  expect(await charge(page.getByTestId('ability-dash'))).toBe(1)
  await page.keyboard.down('KeyW');await page.keyboard.press('Space')
  await expect(page.locator('.movement-spread-hint')).toHaveCount(0)
  await page.keyboard.up('KeyW')
  await page.screenshot({path:'skill-icons-preview.png'})
  expect(errors).toEqual([])
})

test('multiplayer icons refill from server cooldowns and show the equipped ultimate',async({page})=>{
  const errors=[];page.on('pageerror',error=>errors.push(error.message))
  await presetLoadout(page,{character:'aegis',unique:'smoke'})
  await openGame(page);await openMultiplayer(page,'casual','Skill Pilot')
  const peer=await new Client('http://127.0.0.1:2567').joinById(await page.getByTestId('invite-code').textContent(),{name:'Skill Peer'})
  peer.onMessage('loadout-bank',()=>{});peer.onMessage('shot-trail',()=>{})
  try {
    await page.getByLabel('Match format').selectOption('freeplay')
    peer.send('ready',{ready:true})
    await page.getByRole('button',{name:'READY UP',exact:true}).click()
    await page.getByRole('button',{name:'ENTER ARENA',exact:true}).click()
    await expect(page.getByTestId('ability-smoke').locator('.skill-icon-fill svg')).toHaveAttribute('data-skill-icon','smoke')
    await expect(page.getByTestId('ability-ultimate').locator('.skill-icon-fill svg')).toHaveAttribute('data-skill-icon','ultimate-shield')
    await page.keyboard.press('KeyF')
    const shield=page.getByTestId('ability-shield')
    await expect(shield.getByRole('progressbar',{name:'SHIELD cooldown'})).toBeAttached()
    const initial=await charge(shield)
    await expect.poll(()=>charge(shield)).toBeGreaterThan(initial+.05)
    expect(peer.state.players.get(peer.state.hostId).abilities.get('shield').readyAt).toBeGreaterThan(0)
    await page.keyboard.press('KeyX')
    await expect(page.getByTestId('ability-ultimate')).toHaveClass(/active/)
    await page.screenshot({path:'online-skill-icons-preview.png'})
    expect(errors).toEqual([])
  } finally {await peer.leave().catch(()=>{})}
})
