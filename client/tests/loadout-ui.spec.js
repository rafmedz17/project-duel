import {test,expect} from '@playwright/test'
import {editLoadout} from './helpers.js'

test('dashboard inspects without saving, opens accessible pickers and automatically persists every equipment type',async({page})=>{
  test.setTimeout(90000)
  const errors=[];page.on('pageerror',error=>errors.push(error.message))
  await page.goto('/')
  await page.getByRole('button',{name:/^CHARACTER & LOADOUT/}).click()
  const dialog=page.getByRole('dialog',{name:'CHARACTER & LOADOUT',exact:true})
  await expect(dialog.getByRole('button',{name:/^(SAVE|APPLY)/})).toHaveCount(0)
  const stored=()=>page.evaluate(()=>localStorage.getItem('duel-loadout-bank'))
  const before=await stored()
  await dialog.getByRole('button',{name:'Change unique skill',exact:true}).hover()
  await expect(dialog.getByRole('region',{name:'FLASHBANG details'})).toBeVisible()
  await dialog.getByRole('button',{name:'Change primary gun',exact:true}).hover()
  await expect(dialog.getByRole('region',{name:'VXR-9 PHANTOM details'})).toBeVisible()
  expect(await stored()).toBe(before)
  await page.screenshot({path:'loadout-dashboard-preview.png'})
  await dialog.getByRole('button',{name:'Change character',exact:true}).click()
  const characters=page.getByRole('dialog',{name:'CHOOSE YOUR OPERATIVE',exact:true})
  await expect(characters.locator('.operative-option')).toHaveCount(4)
  await expect(characters).toHaveAttribute('aria-modal','true')
  await page.keyboard.press('Shift+Tab')
  await expect(characters.getByRole('button',{name:'Select RAZE',exact:true})).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(characters.getByRole('button',{name:'Close equipment picker',exact:true})).toBeFocused()
  await characters.screenshot({path:'loadout-character-picker-preview.png'})
  await page.keyboard.press('Escape')
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('button',{name:'Change character',exact:true})).toBeFocused()
  expect(await stored()).toBe(before)
  await dialog.getByRole('button',{name:'Change primary gun',exact:true}).click()
  const weapons=page.getByRole('dialog',{name:'PRIMARY ARSENAL',exact:true})
  await expect(weapons.locator('.weapon-category')).toHaveCount(5)
  await expect(weapons.locator('.weapon-option')).toHaveCount(11)
  await weapons.getByRole('button',{name:'Equip HYPERION X',exact:true}).hover()
  await expect(weapons.getByRole('region',{name:'HYPERION X details'})).toBeVisible()
  await weapons.screenshot({path:'loadout-primary-picker-preview.png'})
  await page.keyboard.press('Escape')
  expect(await stored()).toBe(before)
  await editLoadout(page,{character:'aegis',primary:'hyperion',secondary:'volt',melee:'gravity',unique:'scanner'})
  await expect(dialog.getByRole('button',{name:'View ultimate skill',exact:true})).toContainText('FORTRESS PROTOCOL')
  await dialog.getByRole('button',{name:'View ultimate skill',exact:true}).click()
  const ultimate=page.getByRole('dialog',{name:'FORTRESS PROTOCOL',exact:true})
  await expect(ultimate).toContainText('200-point shield')
  await page.keyboard.press('Escape')
  const saved=JSON.parse(await stored())
  expect(saved.slots[0]).toMatchObject({character:'aegis',primary:'hyperion',secondary:'volt',melee:'gravity',unique:'scanner',startingWeapon:'hyperion'})
  await page.setViewportSize({width:390,height:844})
  expect(await dialog.evaluate(element=>element.scrollWidth<=element.clientWidth+1)).toBe(true)
  await dialog.getByRole('button',{name:'Change primary gun',exact:true}).scrollIntoViewIfNeeded()
  await page.screenshot({path:'loadout-mobile-preview.png'})
  await dialog.getByRole('button',{name:'Change primary gun',exact:true}).click()
  expect(await page.getByRole('dialog',{name:'PRIMARY ARSENAL',exact:true}).evaluate(element=>element.scrollWidth<=element.clientWidth+1)).toBe(true)
  await page.keyboard.press('Escape')
  expect(errors).toEqual([])
})
