import { test, expect } from '@playwright/test'
import { state, diagnostics, position, moveUntil, aimAtTarget } from './helpers.js'
async function pause(page) {
  // Browser automation cannot synthesize the browser-owned Escape shortcut.
  await page.evaluate(() => document.exitPointerLock())
  await expect.poll(async () => (await state(page)).mode).toBe('paused')
}
async function resume(page) {
  await page.getByRole('button', { name: 'RESUME / ENTER ARENA' }).click()
  await expect.poll(async () => (await state(page)).mode).toBe('playing')
}

test('menus, persistent settings, movement, collisions, combat, pause and reset', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: /PROJECT.*DUEL/ })).toBeVisible()
  await page.getByRole('button', { name: /CONTROLS/ }).click()
  await expect(page.getByText('Fire / swing equipped weapon', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'BACK' }).click()
  await page.getByRole('button', { name: /SETTINGS/ }).click()
  await page.getByLabel('Render quality').selectOption('Low')
  await page.getByLabel('Show FPS counter').check()
  await page.getByRole('button', { name: 'BACK' }).click()
  await page.reload()
  expect((await state(page)).settings).toMatchObject({ quality:'Low', fps:true })
  await page.getByRole('button', { name: /ENTER TRAINING/ }).click()
  await expect(page.getByRole('button', { name: 'RESUME / ENTER ARENA' })).toBeEnabled({ timeout:30000 })
  await resume(page)
  await expect.poll(async () => (await position(page))[1]).toBeLessThan(0.92)
  const initial = await position(page)
  await page.keyboard.down('KeyW'); await page.waitForTimeout(700); await page.keyboard.up('KeyW')
  const walk = await position(page)
  expect(walk[2]).toBeLessThan(initial[2]-1)
  await page.keyboard.down('ShiftLeft'); await page.keyboard.down('KeyW'); await page.waitForTimeout(700); await page.keyboard.up('KeyW'); await page.keyboard.up('ShiftLeft')
  const sprint = await position(page)
  expect(walk[2]-sprint[2]).toBeGreaterThan(initial[2]-walk[2])
  await page.keyboard.press('Space')
  await expect.poll(async () => (await diagnostics(page)).peakHeight).toBeGreaterThan(1.2)
  await page.waitForTimeout(1000)
  expect((await position(page))[1]).toBeLessThan(0.92)
  // Move through the central lane, then verify the visible north boundary stops us.
  await page.keyboard.down('ShiftLeft'); await page.keyboard.down('KeyW'); await page.waitForTimeout(5500); await page.keyboard.up('KeyW'); await page.keyboard.up('ShiftLeft')
  expect((await position(page))[2]).toBeGreaterThan(-19.3)
  expect((await position(page))[2]).toBeLessThan(-18)
  await pause(page)
  const frozen = await position(page), time = (await state(page)).time
  await page.keyboard.down('KeyW'); await page.mouse.click(50,400); await page.waitForTimeout(300); await page.keyboard.up('KeyW')
  expect(await position(page)).toEqual(frozen)
  expect((await state(page)).time).toBe(time)
  await page.getByRole('button', { name:'RESTART TRAINING', exact:true }).click()
  await resume(page)
  await page.waitForTimeout(200)
  expect((await position(page))[2]).toBeCloseTo(15,0)
  // Real mouse look aims at target 02 from the spawn. No hit result is injected.
  await aimAtTarget(page)
  await page.screenshot({ path:'training-preview.png' })
  for (let i=0;i<5;i++) { await page.mouse.down(); await page.mouse.up(); await page.waitForTimeout(280) }
  let s = await state(page)
  expect(s.magazines.pistol).toBe(7); expect(s.score).toBe(100); expect(s.targets[1].hp).toBe(0)
  await page.keyboard.press('KeyR')
  expect((await state(page)).reloading).toBe(true)
  await page.mouse.down(); await page.mouse.up()
  expect((await state(page)).magazines.pistol).toBe(7)
  await page.waitForTimeout(1700)
  expect((await state(page)).magazines.pistol).toBe(12)
  await page.waitForTimeout(1700)
  expect((await state(page)).targets[1].hp).toBe(100)
  await pause(page)
  await page.getByRole('button', { name:'RESTART TRAINING',exact:true }).click()
  s = await state(page)
  expect(s).toMatchObject({ hp:100, magazines:{ pistol:12,rifle:30,shotgun:6 }, score:0, hits:0, shots:0 })
  await page.getByRole('button', { name:'RETURN TO MAIN MENU' }).click()
  await expect(page.getByRole('button', { name:/ENTER TRAINING/ })).toBeVisible()
  expect(errors).toEqual([])
})

test('cover blocks the capsule and marked hazards damage and defeat the player', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByRole('button', { name:/SETTINGS/ }).click()
  await page.getByLabel('Render quality').selectOption('Low')
  await page.getByRole('button', { name:'BACK' }).click()
  await page.getByRole('button', { name:/ENTER TRAINING/ }).click()
  await expect(page.getByRole('button', { name:'RESUME / ENTER ARENA' })).toBeEnabled({ timeout:30000 })
  await resume(page)
  await moveUntil(page,'KeyD',0,7.7,1)
  await page.keyboard.down('KeyW'); await page.waitForTimeout(2400); await page.keyboard.up('KeyW')
  const coverPosition = await position(page)
  expect(coverPosition[2]).toBeGreaterThan(7.3)
  expect(coverPosition[2]).toBeLessThan(7.6)
  await moveUntil(page,'KeyD',0,14.7,1)
  await moveUntil(page,'KeyW',2,3.3,-1)
  const padPosition = await position(page)
  expect(padPosition[0]).toBeGreaterThan(13.5); expect(padPosition[0]).toBeLessThan(16.5)
  expect(padPosition[2]).toBeGreaterThan(1.5); expect(padPosition[2]).toBeLessThan(4.5)
  await expect.poll(async () => (await state(page)).hp,{ timeout:3000 }).toBeLessThan(100)
  await expect.poll(async () => (await state(page)).mode,{ timeout:12000 }).toBe('dead')
  expect((await state(page)).hp).toBe(0)
  expect(await page.evaluate(() => document.pointerLockElement === null)).toBe(true)
  await expect(page.getByRole('heading', { name:'SYSTEM OFFLINE' })).toBeVisible()
  await page.getByRole('button', { name:'RESTART TRAINING',exact:true }).click()
  expect((await state(page)).hp).toBe(100)
  expect(errors).toEqual([])
})
