test('versus cards show both players and host settings synchronize and reset readiness',async({browser})=>{
  const hostContext=await browser.newContext({reducedMotion:'reduce'}),guestContext=await browser.newContext({reducedMotion:'reduce'})
  const host=await hostContext.newPage(),guest=await guestContext.newPage()
  try {
    await openGame(host);await openMultiplayer(host,'casual','Nova')
    await expect(host.getByTestId('invite-code')).toHaveText(/^[A-HJ-NP-Z2-9]{6}$/)
    const code=await host.getByTestId('invite-code').textContent()
    await openGame(guest);await openMultiplayer(guest,'casual','Echo')
    await guest.getByLabel('INVITE CODE',{exact:true}).fill(code)
    await guest.getByRole('button',{name:'JOIN ROOM',exact:true}).click()
    for(const page of [host,guest]) {
      await expect(page.getByTestId('lobby-slot-0')).toContainText('Nova')
      await expect(page.getByTestId('lobby-slot-1')).toContainText('Echo')
    }
    await expect(guest.getByLabel('Match format')).toBeDisabled()
    await expect(guest.getByLabel('Arena map')).toBeDisabled()
    await host.getByLabel('Match format').selectOption('freeplay')
    await expect(guest.getByLabel('Match format')).toHaveValue('freeplay')
    await host.getByRole('button',{name:'READY UP',exact:true}).click()
    await guest.getByRole('button',{name:'READY UP',exact:true}).click()
    await expect(host.getByText(/BOTH PLAYERS READY.*STARTING IN/)).toBeVisible()
    await guest.getByRole('button',{name:'CANCEL READY',exact:true}).click()
    await expect(host.getByLabel('Arena map')).toBeEnabled()
    await host.getByLabel('Arena map').selectOption('orbital')
    await expect(guest.getByLabel('Arena map')).toHaveValue('orbital')
    await expect(guest.getByRole('button',{name:'READY UP',exact:true})).toBeVisible()
    await expect(host.getByRole('button',{name:'START SHARED ARENA',exact:true})).toHaveCount(0)
    await host.screenshot({path:'lobby-connected-preview.png'})
  } finally {await Promise.all([hostContext.close(),guestContext.close()])}
})
