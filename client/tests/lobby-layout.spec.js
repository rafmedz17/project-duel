import {test,expect} from '@playwright/test'
import {openGame,openMultiplayer} from './helpers.js'

test('multiplayer opens an anchored mode picker with keyboard navigation and dismisses back to its button',async({page})=>{
  await openGame(page)
  const launcher=page.getByRole('button',{name:/^MULTIPLAYER/})
  await launcher.click()
  const picker=page.getByRole('dialog',{name:'Choose multiplayer mode',exact:true})
  await expect(picker).toBeVisible();await expect(launcher).toHaveAttribute('aria-expanded','true')
  await expect(picker.getByRole('button',{name:/^CASUAL /})).toBeFocused()
  const buttonBox=await launcher.boundingBox(),pickerBox=await picker.boundingBox()
  expect(pickerBox.x+pickerBox.width).toBeLessThan(buttonBox.x)
  expect(Math.abs(pickerBox.y+pickerBox.height/2-buttonBox.y-buttonBox.height/2)).toBeLessThan(5)
  await page.screenshot({path:'multiplayer-mode-picker-preview.png'})
  await page.keyboard.press('ArrowDown')
  await expect(picker.getByRole('button',{name:/^RANKED /})).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(picker).toHaveCount(0);await expect(launcher).toBeFocused()
  await launcher.click();await page.getByRole('heading',{name:/PROJECT.*DUEL/}).click()
  await expect(picker).toHaveCount(0)
})

test('casual immediately creates a room with a copyable code, separate join field and a responsive versus layout',async({page})=>{
  const errors=[];page.on('pageerror',error=>errors.push(error.message))
  await openGame(page);await openMultiplayer(page)
  const dialog=page.getByRole('dialog',{name:'PRIVATE MULTIPLAYER',exact:true})
  await expect(dialog).toContainText('CASUAL MATCH')
  await expect(page.getByTestId('invite-code')).toHaveText(/^[A-HJ-NP-Z2-9]{6}$/)
  await expect(page.getByRole('button',{name:'COPY CODE',exact:true})).toBeEnabled()
  await expect(page.getByLabel('INVITE CODE',{exact:true})).toBeEditable()
  const left=await page.getByTestId('lobby-slot-0').boundingBox(),right=await page.getByTestId('lobby-slot-1').boundingBox(),center=await page.getByLabel('Match format').boundingBox()
  expect(left.x+left.width).toBeLessThan(center.x);expect(center.x+center.width).toBeLessThan(right.x)
  expect(Math.abs(left.y-right.y)).toBeLessThan(2)
  await expect(page.getByLabel('Arena map')).toBeEnabled()
  await expect(page.getByRole('button',{name:'CREATE PRIVATE ROOM',exact:true})).toHaveCount(0)
  await page.screenshot({path:'lobby-create-preview.png'})
  await page.setViewportSize({width:390,height:844})
  expect(await dialog.evaluate(element=>element.scrollWidth<=element.clientWidth)).toBe(true)
  await page.getByRole('button',{name:'READY UP',exact:true}).scrollIntoViewIfNeeded()
  await page.screenshot({path:'lobby-mobile-preview.png'})
  await page.getByRole('button',{name:'LEAVE ROOM',exact:true}).click()
  await expect(dialog).toHaveCount(0);expect(errors).toEqual([])
})

