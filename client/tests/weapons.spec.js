import { test, expect } from '@playwright/test'
import { state, lookAt, aimAtTarget, moveUntil } from './helpers.js'
import { TARGETS } from '../src/game/config.js'

const attack = async page => { await page.mouse.down(); await page.mouse.up() }

test('blade switching, range, melee damage, ammo preservation, pause and restart', async ({ page }) => {
  const errors = []
  page.on('pageerror',error => errors.push(error.message))
  await page.goto('/')
  await page.getByRole('button',{ name:/CONTROLS/ }).click()
  await expect(page.getByText('Primary / Pistol / Melee',{ exact:true })).toBeVisible()
  await page.getByRole('button',{ name:'BACK' }).click()
  await page.getByRole('button',{ name:/SETTINGS/ }).click()
  await page.getByLabel('Render quality').selectOption('Low')
  await page.getByRole('button',{ name:'BACK' }).click()
  await page.getByRole('button',{ name:/ENTER TRAINING/ }).click()
  await expect(page.getByRole('button',{ name:'RESUME / ENTER ARENA' })).toBeEnabled({ timeout:30000 })
  await page.getByRole('button',{ name:'RESUME / ENTER ARENA' }).click()
  await expect.poll(async () => (await state(page)).mode).toBe('playing')
  await attack(page)
  await page.waitForTimeout(300)
  expect((await state(page)).magazines.pistol).toBe(14)
  await page.keyboard.press('KeyR')
  expect((await state(page)).reloading).toBe(true)
  await page.keyboard.press('Digit3')
  expect((await state(page)).weapon).toBe('blade')
  expect((await state(page)).reloading).toBe(false)
  await expect(page.getByText('3 / PHANTOM EDGE',{ exact:true })).toBeVisible()
  await expect(page.locator('.ammo').getByText('READY',{ exact:true })).toBeVisible()
  await aimAtTarget(page)
  await attack(page)
  expect((await state(page)).swings).toBe(1)
  expect((await state(page)).targets[1].hp).toBe(100) // aimed correctly, but far outside melee reach
  expect((await state(page)).magazines.pistol).toBe(14)
  await page.keyboard.press('KeyR')
  expect((await state(page)).reloading).toBe(false)
  await page.waitForTimeout(850)
  await page.keyboard.press('KeyQ')
  expect((await state(page)).weapon).toBe('rifle')
  await page.waitForTimeout(300)
  await page.keyboard.press('Digit3')
  await lookAt(page,0,0)
  // Navigate through the open central lane, then approach target 02 from the south.
  await moveUntil(page,'KeyW',2,-12.8,-1)
  await moveUntil(page,'KeyA',0,TARGETS[1][0]+0.1,-1)
  await moveUntil(page,'KeyW',2,-14,-1)
  await aimAtTarget(page)
  await page.screenshot({ path:'blade-preview.png' })
  await attack(page)
  expect((await state(page)).targets[1].hp).toBe(50)
  expect((await state(page)).hitDamage).toBe(50)
  await attack(page)
  expect((await state(page)).swings).toBe(2)
  expect((await state(page)).targets[1].hp).toBe(50)
  await page.waitForTimeout(850)
  await attack(page)
  const defeated = await state(page)
  expect(defeated.targets[1].hp).toBe(0)
  expect(defeated.hitDamage).toBe(50)
  expect(defeated.score).toBe(100)
  expect(defeated.meleeHits).toBe(2)
  expect(defeated.shots).toBe(1)
  expect(defeated.hits).toBe(0)
  await page.evaluate(() => document.exitPointerLock())
  await expect.poll(async () => (await state(page)).mode).toBe('paused')
  const paused = await state(page)
  await page.keyboard.press('Digit2'); await page.keyboard.press('KeyQ'); await page.keyboard.press('KeyR')
  await page.mouse.click(50,400)
  expect((await state(page)).weapon).toBe('blade')
  expect((await state(page)).swings).toBe(paused.swings)
  expect((await state(page)).time).toBe(paused.time)
  await page.getByRole('button',{ name:'RESUME / ENTER ARENA' }).click()
  await page.waitForTimeout(400)
  await page.keyboard.press('Digit2')
  expect((await state(page)).magazines.pistol).toBe(14)
  await page.waitForTimeout(300)
  await page.keyboard.press('KeyR')
  await expect.poll(async () => (await state(page)).magazines.pistol).toBe(15)
  await page.evaluate(() => document.exitPointerLock())
  await page.getByRole('button',{ name:'RESTART TRAINING',exact:true }).click()
  expect(await state(page)).toMatchObject({ weapon:'pistol',magazines:{ pistol:15,rifle:30,shotgun:6 },swings:0,meleeHits:0,score:0,attackReadyAt:0 })
  expect(errors).toEqual([])
})
